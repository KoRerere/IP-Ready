export function useI18n() {
  const locale = useState<Locale>('locale', () => 'en')
  const t = (key: string) => messages[locale.value][key] ?? messages.en[key] ?? key
  const setLocale = (next: Locale) => { locale.value = next }
  return { locale, t, setLocale }
}
